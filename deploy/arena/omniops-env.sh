#!/usr/bin/env bash
# Write the OmniOps source environment for the Arena cluster to .state/omniops.env (mode 600) and
# print it with every secret masked. The benchmark runner loads this file; for 'omniops serve' or the
# CLI run:  set -a; source deploy/arena/.state/omniops.env; set +a
#
# GITHUB_TOKEN is never written here: export it yourself, preferably a read-only fine-grained PAT
# (Contents + Metadata: read on the two repositories; `gh auth token` works but carries write scopes).
# OMNIOPS_ARENA_FAULT_REPO_ACCESS=1 also lists the fault repository in GITHUB_REPOS (it changes the
# evidence OmniOps can see; the runner records the choice in every run).
#
# Kubernetes: OmniOps gets no cluster credential (never the kind admin kubeconfig: with it, the Arena's
# benchmark-control/suite-state ConfigMap, which names the active scenario, shows up in OmniOps'
# configmaps table and change feed). Its kubeconfig (.state/omniops-kubeconfig, context omniops-arena)
# points at port-forward.sh's read-only, namespace-filtering proxy. KUBECONFIG lists your own file
# second, so 'kubectl --context kind-...' keeps working in a shell that sourced this file; OmniOps
# reads only the first entry.
source "$(dirname "$0")/lib.sh"

OUT="$STATE_DIR/omniops.env"
KUBE_VIEW="$STATE_DIR/omniops-kubeconfig"
ensure_state_dir

secret_or_empty() { [ -f "$1" ] && tr -d '\n' <"$1" || true; }

helper kubeconfig --server "http://127.0.0.1:$KUBE_PROXY_PORT" --context "$OMNIOPS_KUBE_CONTEXT" --out "$KUBE_VIEW"
own_kubeconfig="${KUBECONFIG:-$HOME/.kube/config}"
own_kubeconfig="${own_kubeconfig#"$KUBE_VIEW:"}"          # rerun from a shell that sourced the env file

grafana_token="$(secret_or_empty "$STATE_DIR/grafana-token")"
argocd_token="$(secret_or_empty "$STATE_DIR/argocd-token")"
slack_mode="$(secret_or_empty "$STATE_DIR/slack-contact-point")"
fault_access="${OMNIOPS_ARENA_FAULT_REPO_ACCESS:-0}"

owner="" repos=""
if [ -f "$STATE_DIR/arena-gitops.json" ]; then
  owner="$("$PY" -c 'import json,sys,re; u=json.load(open(sys.argv[1]))["gitops"]["app_repo"]["url"]; print(re.sub(r"^https://github.com/([^/]+)/.*$", r"\1", u))' "$STATE_DIR/arena-gitops.json")"
  repos="$owner/${ARENA_APP_REPO:-service-manifests}"
  if [ "$fault_access" = 1 ]; then repos="$repos,$owner/${ARENA_FAULT_REPO:-platform-config}"; fi
fi

{
  echo "# OmniOps sources for the Arena cluster (generated by deploy/arena/omniops-env.sh; contains secrets)"
  echo "KUBECONFIG=\"$KUBE_VIEW:$own_kubeconfig\""
  echo "KUBE_CONTEXT=\"$OMNIOPS_KUBE_CONTEXT\""
  echo "KUBERNETES_CONTEXT=\"$OMNIOPS_KUBE_CONTEXT\""
  echo "K8S_API_URL=\"http://127.0.0.1:$KUBE_PROXY_PORT\""
  echo "OMNIOPS_ARENA_KUBE_HIDDEN_NAMESPACES=\"$KUBE_HIDDEN_NAMESPACES\""
  echo "GRAFANA_URL=\"http://localhost:$GRAFANA_PORT\""
  echo "GRAFANA_TOKEN=\"$grafana_token\""
  echo "GRAFANA_PROMETHEUS_UID=\"prometheus\""
  echo "GRAFANA_LOKI_UID=\"loki\""
  echo "GRAFANA_TEMPO_UID=\"tempo\""
  echo "PROMETHEUS_URL=\"http://localhost:$PROMETHEUS_PORT\""
  echo "LOKI_URL=\"http://localhost:$LOKI_PORT\""
  echo "TEMPO_URL=\"http://localhost:$TEMPO_PORT\""
  echo "ALERTMANAGER_URL=\"http://localhost:$GRAFANA_PORT/api/alertmanager/grafana\""
  echo "ALERTMANAGER_TOKEN=\"$grafana_token\""
  if argocd_installed; then
    echo "ARGOCD_URL=\"http://localhost:$ARGOCD_PORT\""
    echo "ARGOCD_TOKEN=\"$argocd_token\""
    echo "OMNIOPS_ARENA_ARGOCD_HIDDEN_APPS=\"$ARGOCD_HIDDEN_APPS\""
  fi
  if [ -n "$owner" ]; then
    echo "GITHUB_OWNER=\"$owner\""
    echo "GITHUB_REPOS=\"$repos\""
  fi
  echo "OMNIOPS_ARENA_FAULT_REPO_ACCESS=\"$fault_access\""
  echo "OMNIOPS_ARENA_BRIDGE_PORT=\"$BRIDGE_PORT\""
  if [ "$slack_mode" = webhook ] || [ "$slack_mode" = token ]; then
    echo "OMNIOPS_ARENA_GRAFANA_POSTS=\"1\""
  fi
  if [ -n "${OMNIOPS_ARENA_CHANNEL:-}" ]; then
    echo "OMNIOPS_ARENA_CHANNEL=\"$OMNIOPS_ARENA_CHANNEL\""
    echo "OMNIOPS_ALERT_CHANNELS=\"$OMNIOPS_ARENA_CHANNEL\""
  fi
} | write_private "$OUT"
grafana_token="" argocd_token=""

log "Wrote $OUT (mode 600). Contents with secrets masked:"
sed -E 's/^([A-Z_]*(TOKEN|PASSWORD|SECRET)[A-Z_]*)="[^"]+"/\1="<set>"/' "$OUT" | sed 's/^/    /'
grep -q '^GRAFANA_TOKEN="."' "$OUT" || warn "GRAFANA_TOKEN is empty: run deploy/arena/observability.sh install"
[ -s "$STATE_DIR/kube-upstream.json" ] ||
  warn "OmniOps' Kubernetes view has no read-only identity yet: run deploy/arena/port-forward.sh stop, then start"
if argocd_installed; then grep -q '^ARGOCD_TOKEN="."' "$OUT" || warn "ARGOCD_TOKEN is empty: run deploy/arena/argocd.sh token"; fi
[ -n "$owner" ] || note "No GitOps repositories yet: GITHUB_REPOS is unset (direct deployment has no Git history)."
