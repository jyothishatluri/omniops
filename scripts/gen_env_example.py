"""Regenerate the "Data sources" section of .env.example from the manifests.

The part above the "Data sources" banner (LLM, Slack, OmniOps settings) is hand-written and kept.
Required variables are listed uncommented and empty; optional ones are commented with their default.

    uv run --no-sync python scripts/gen_env_example.py
"""

from __future__ import annotations

from pathlib import Path

from omniops.engine.loader import load_all_manifests

ROOT = Path(__file__).resolve().parents[1]
ENV_EXAMPLE = ROOT / ".env.example"
BANNER = "# " + "=" * 93


def main() -> None:
    text = ENV_EXAMPLE.read_text()
    lines = text.splitlines()
    title = next((i for i, line in enumerate(lines) if line.startswith("# Data sources")), None)
    if title is None:
        raise SystemExit(".env.example has no '# Data sources' banner")
    head = lines[: title - 1]
    manifests, _ = load_all_manifests(strict=False)
    out = head + [BANNER, "# Data sources (generated by scripts/gen_env_example.py from the manifests; a source is",
                  "# enabled when all of its uncommented variables are set)", BANNER, ""]
    seen: set[str] = set()
    for m in sorted(manifests.values(), key=lambda m: (m.vendor or m.display_name).lower() + m.source):
        names = list(dict.fromkeys(m.required_env + [e.name for e in m.env]))
        names = [n for n in names if n not in seen]
        if not names:
            continue
        out.append(f"# --- {m.display_name} ({m.source}) ".ljust(95, "-"))
        by_name = {e.name: e for e in m.env}
        for n in names:
            seen.add(n)
            e = by_name.get(n)
            if e is not None and e.description:
                out.append(f"# {' '.join(e.description.split())[:200]}")
            if n in m.required_env:
                out.append(f"{n}=")
            else:
                default = "" if e is None or e.secret or e.default is None else e.default
                out.append(f"# {n}={default}")
        out.append("")
    ENV_EXAMPLE.write_text("\n".join(out).rstrip() + "\n")
    print(f"wrote {ENV_EXAMPLE} ({len(seen)} source variables)")


if __name__ == "__main__":
    main()
